class ReferralService:
    """Authoritative business logic for referral attribution, analytics, and commissions."""

    @staticmethod
    async def validate_referral_code(db: AsyncSession, code: str) -> Dict[str, Any]:
        """Validate if a referral code exists and return the referrer's public identity."""
        if not code or not code.strip():
            return {"valid": False, "message": "Referral code cannot be empty."}
        clean = code.strip().upper()
        res = await db.execute(
            select(User).filter(func.upper(func.trim(User.referral_code)) == clean)
        )
        referrer = res.scalars().first()
        if not referrer:
            return {"valid": False, "message": "Referral code does not exist."}
        return {
            "valid": True,
            "referral_code": referrer.referral_code,
            "referrer_name": referrer.full_name,
            "message": f"Valid invitation from {referrer.full_name}.",
        }

    @staticmethod
    async def get_user_referrals(db: AsyncSession, user_id: uuid.UUID) -> List[Dict[str, Any]]:
        """Fetch all users attributed to this referrer with rich deposit, investment, and commission telemetry."""
        result = await db.execute(
            select(User).filter(User.referred_by == user_id).order_by(User.created_at.desc())
        )
        referees = result.scalars().all()

        telemetry_list = []
        for ref in referees:
            # 1. Deposit activity
            dep_res = await db.execute(
                select(DepositRequest).filter(DepositRequest.user_id == ref.id)
            )
            deposits = dep_res.scalars().all()
            verified_deposits = [d for d in deposits if d.status == "verified"]
            pending_deposits = [d for d in deposits if d.status == "pending"]
            total_dep = sum(float(d.amount) for d in verified_deposits)
            dep_status = "none"
            if verified_deposits:
                dep_status = "verified"
            elif pending_deposits:
                dep_status = "pending"

            # 2. Investment activity
            inv_res = await db.execute(
                select(Investment).filter(Investment.user_id == ref.id)
            )
            investments = inv_res.scalars().all()
            active_invs = [i for i in investments if i.status == "active"]
            completed_invs = [i for i in investments if i.status in ["completed", "matured"]]
            has_invested = len(investments) > 0
            inv_status = "none"
            if active_invs:
                inv_status = "active"
            elif completed_invs:
                inv_status = "completed"

            # 3. Commission generated by this referee for current user
            comm_res = await db.execute(
                select(ReferralCommission).filter(
                    ReferralCommission.referrer_id == user_id,
                    ReferralCommission.referred_user_id == ref.id,
                )
            )
            comms = comm_res.scalars().all()
            total_comm = sum(float(c.commission_amount) for c in comms if c.status == "paid")
            comm_status = "none"
            if any(c.status == "paid" for c in comms):
                comm_status = "paid"
            elif any(c.status == "pending" for c in comms):
                comm_status = "pending"

            # 4. Qualifying Activity Description
            if active_invs:
                qualifying_act = f"Active Plan (${float(active_invs[0].amount):,.2f})"
            elif completed_invs:
                qualifying_act = f"Completed Plan (${float(completed_invs[0].amount):,.2f})"
            elif verified_deposits:
                qualifying_act = f"Funded (${total_dep:,.2f})"
            elif pending_deposits:
                qualifying_act = "Deposit Pending"
            else:
                qualifying_act = "Registered"

            telemetry_list.append({
                "id": str(ref.id),
                "full_name": ref.full_name,
                "email": ref.email,
                "created_at": ref.created_at.isoformat() if ref.created_at else datetime.utcnow().isoformat(),
                "kyc_status": ref.kyc_status or "not_started",
                "has_deposited": len(verified_deposits) > 0,
                "total_deposited": total_dep,
                "deposit_status": dep_status,
                "has_invested": has_invested,
                "active_investments_count": len(active_invs),
                "investment_status": inv_status,
                "qualifying_activity": qualifying_act,
                "total_commission_earned": total_comm,
                "commission_status": comm_status,
            })

        return telemetry_list

    @staticmethod
    async def get_referral_commissions(
        db: AsyncSession, user_id: uuid.UUID, status_filter: Optional[str] = None
    ) -> List[Dict[str, Any]]:
        """Fetch all referral commissions earned by this user with enriched referee and plan labels."""
        query = select(ReferralCommission, User).join(User, ReferralCommission.referred_user_id == User.id).filter(
            ReferralCommission.referrer_id == user_id
        )
        if status_filter:
            query = query.filter(ReferralCommission.status == status_filter.lower())
        result = await db.execute(query.order_by(ReferralCommission.created_at.desc()))
        
        commission_list = []
        for comm, referee in result.all():
            plan_name = None
            if comm.investment_id:
                inv_res = await db.execute(
                    select(Investment, InvestmentPlan)
                    .join(InvestmentPlan, Investment.plan_id == InvestmentPlan.id)
                    .filter(Investment.id == comm.investment_id)
                )
                inv_row = inv_res.first()
                if inv_row:
                    plan_name = inv_row[1].name

            commission_list.append({
                "id": str(comm.id),
                "referrer_id": str(comm.referrer_id),
                "referred_user_id": str(comm.referred_user_id),
                "referred_user_name": referee.full_name if referee else "Referral Partner",
                "investment_id": str(comm.investment_id) if comm.investment_id else None,
                "deposit_id": str(comm.deposit_id) if comm.deposit_id else None,
                "plan_name": plan_name,
                "source_type": comm.source_type or "investment",
                "commission_amount": float(comm.commission_amount),
                "currency": comm.currency,
                "level": comm.level,
                "status": comm.status,
                "created_at": comm.created_at.isoformat() if comm.created_at else None,
                "paid_at": comm.paid_at.isoformat() if comm.paid_at else None,
            })

        return commission_list

    async def get_referral_stats(self, db: AsyncSession, user_id: uuid.UUID) -> Dict[str, Any]:
        """Generate authoritative referral metrics, reconciling and synchronizing counts dynamically."""
        user_result = await db.execute(select(User).filter(User.id == user_id))
        user = user_result.scalars().first()

        if user is None:
            return {
                "referral_code": "",
                "referral_count": 0,
                "active_referrals_count": 0,
                "referral_earnings": 0.0,
                "pending_earnings": 0.0,
                "pending_commissions": {},
                "paid_commissions": {},
            }

        # 1. Authoritative referral count from database
        ref_count_res = await db.execute(
            select(func.count(User.id)).filter(User.referred_by == user_id)
        )
        actual_ref_count = ref_count_res.scalar() or 0

        # 2. Active / Qualifying referrals (referees who made a deposit or investment)
        referee_ids_res = await db.execute(select(User.id).filter(User.referred_by == user_id))
        referee_ids = list(referee_ids_res.scalars().all())

        active_ref_count = 0
        if referee_ids:
            dep_res = await db.execute(
                select(DepositRequest.user_id)
                .filter(DepositRequest.user_id.in_(referee_ids))
                .filter(DepositRequest.status == "verified")
                .distinct()
            )
            active_uids = set(dep_res.scalars().all())

            inv_res = await db.execute(
                select(Investment.user_id)
                .filter(Investment.user_id.in_(referee_ids))
                .filter(Investment.status.in_(["active", "completed", "matured"]))
                .distinct()
            )
            active_uids.update(inv_res.scalars().all())
            active_ref_count = len(active_uids)

        # 3. Calculate pending and paid commissions grouped by currency
        commissions_result = await db.execute(
            select(
                ReferralCommission.status,
                ReferralCommission.currency,
                func.sum(ReferralCommission.commission_amount),
            )
            .filter(ReferralCommission.referrer_id == user_id)
            .group_by(ReferralCommission.status, ReferralCommission.currency)
        )

        pending_commissions = {}
        paid_commissions = {}

        for status, currency, total in commissions_result.all():
            currency = currency.upper()
            total_decimal = Decimal(str(total)) if total else Decimal("0.0")
            if status == "pending":
                pending_commissions[currency] = float(total_decimal)
            elif status == "paid":
                paid_commissions[currency] = float(total_decimal)

        # Total earnings aggregated (settled payouts)
        total_paid_earnings = sum(paid_commissions.values())
        total_pending_earnings = sum(pending_commissions.values())

        # 4. Synchronize user record with authoritative calculations if out of sync
        if user.referral_count != actual_ref_count or float(user.referral_earnings or 0.0) != total_paid_earnings:
            user.referral_count = actual_ref_count
            user.referral_earnings = Decimal(str(total_paid_earnings))
            db.add(user)
            await db.commit()
            await db.refresh(user)

        return {
            "referral_code": user.referral_code,
            "referral_count": actual_ref_count,
            "active_referrals_count": active_ref_count,
            "referral_earnings": total_paid_earnings,
            "pending_earnings": total_pending_earnings,
            "pending_commissions": pending_commissions,
            "paid_commissions": paid_commissions,
        }

    @staticmethod
    async def create_investment_referral_commission(
        db: AsyncSession,
        investment: Investment,
        plan: InvestmentPlan,
        referrer_id: uuid.UUID,
        referred_user: User,
    ) -> Optional[ReferralCommission]:
        """Idempotently generate an investment referral commission record and pending ledger transaction."""
        # 1. Uniqueness check: Ensure no duplicate commission for this investment
        existing = await db.execute(
            select(ReferralCommission).filter(ReferralCommission.investment_id == investment.id)
        )
        if existing.scalars().first() is not None:
            return None

        # 2. Check plan referral commission rate
        bonus_pct = plan.referral_bonus_percentage or Decimal("0.0")
        if bonus_pct <= Decimal("0.0"):
            return None

        commission_amount = investment.amount * (bonus_pct / Decimal("100.0"))
        if commission_amount <= Decimal("0.0"):
            return None

        # 3. Create commission record
        commission = ReferralCommission(
            referrer_id=referrer_id,
            referred_user_id=referred_user.id,
            investment_id=investment.id,
            source_type="investment",
            commission_amount=commission_amount,
            currency=investment.currency,
            level=1,
            status="pending",
        )
        db.add(commission)
        await db.flush()

        # 4. Create pending transaction in ledger for referrer
        tx_ref = f"REF-{commission.id.hex[:10].upper()}"
        ref_tx = Transaction(
            user_id=referrer_id,
            type="referral_bonus",
            subtype="affiliate_commission",
            amount=commission_amount,
            fee=Decimal("0.0"),
            currency=investment.currency,
            status="pending",
            reference=tx_ref,
            description=f"Affiliate commission for referral investment in {plan.name}",
            metadata_={
                "referral_commission_id": str(commission.id),
                "investment_id": str(investment.id),
                "referred_user_id": str(referred_user.id),
                "plan_name": plan.name,
            },
        )
        db.add(ref_tx)

        # 5. Notify referrer
        await notification_service.create_notification(
            db,
            user_id=referrer_id,
            type="referral",
            title="Referral Investment Started! 📈",
            message=f"{referred_user.full_name} enrolled in {plan.name} (${float(investment.amount):,.2f} {investment.currency}). Your {float(commission_amount):,.4f} {investment.currency} affiliate bonus is pending maturity.",
        )

        return commission

    @staticmethod
    async def create_deposit_referral_commission(
        db: AsyncSession,
        deposit: DepositRequest,
        referrer_id: uuid.UUID,
        referred_user: User,
    ) -> Optional[ReferralCommission]:
        """Idempotently process referral commission on a verified deposit if configured in site settings."""
        # 1. Uniqueness check
        existing = await db.execute(
            select(ReferralCommission).filter(ReferralCommission.deposit_id == deposit.id)
        )
        if existing.scalars().first() is not None:
            return None

        # 2. Check if a deposit referral percentage is configured in site settings
        setting_res = await db.execute(
            select(SiteSetting).filter(SiteSetting.key == "referral_deposit_commission_percent")
        )
        setting = setting_res.scalars().first()
        bonus_pct = Decimal(str(setting.value)) if setting and setting.value else Decimal("0.0")

        # Notify referrer of deposit activity regardless of whether direct deposit commission > 0
        await notification_service.create_notification(
            db,
            user_id=referrer_id,
            type="referral",
            title="Referral Deposit Verified! 💳",
            message=f"{referred_user.full_name} funded their wallet with {deposit.amount} {deposit.currency}.",
        )

        if bonus_pct <= Decimal("0.0"):
            return None

        commission_amount = deposit.amount * (bonus_pct / Decimal("100.0"))
        if commission_amount <= Decimal("0.0"):
            return None

        # 3. Create settled commission record for deposit
        now = datetime.utcnow()
        commission = ReferralCommission(
            referrer_id=referrer_id,
            referred_user_id=referred_user.id,
            deposit_id=deposit.id,
            source_type="deposit",
            commission_amount=commission_amount,
            currency=deposit.currency,
            level=1,
            status="paid",
            paid_at=now,
        )
        db.add(commission)
        await db.flush()

        # 4. Credit referrer's wallet
        wallet_res = await db.execute(
            select(Wallet).filter(Wallet.user_id == referrer_id, Wallet.currency == deposit.currency)
        )
        ref_wallet = wallet_res.scalars().first()
        if not ref_wallet:
            ref_wallet = Wallet(
                user_id=referrer_id,
                currency=deposit.currency,
                balance=commission_amount,
                frozen_balance=Decimal("0.0"),
                total_deposited=Decimal("0.0"),
                total_withdrawn=Decimal("0.0"),
            )
            db.add(ref_wallet)
        else:
            ref_wallet.balance += commission_amount
            db.add(ref_wallet)

        # 5. Record completed ledger transaction
        ref_tx = Transaction(
            user_id=referrer_id,
            type="referral_bonus",
            subtype="deposit_commission",
            amount=commission_amount,
            fee=Decimal("0.0"),
            currency=deposit.currency,
            status="completed",
            reference=f"REF-DEP-{commission.id.hex[:10].upper()}",
            description=f"Deposit affiliate commission from {referred_user.full_name}",
        )
        db.add(ref_tx)

        # 6. Update referrer's earnings
        referrer_res = await db.execute(select(User).filter(User.id == referrer_id))
        referrer = referrer_res.scalars().first()
        if referrer:
            referrer.referral_earnings = (referrer.referral_earnings or Decimal("0.0")) + commission_amount
            db.add(referrer)

        return commission

    @staticmethod
    async def settle_referral_commission(
        db: AsyncSession,
        commission_id: uuid.UUID,
    ) -> Optional[ReferralCommission]:
        """Settle a pending referral commission, crediting the referrer's wallet and ledger."""
        comm_res = await db.execute(
            select(ReferralCommission).filter(ReferralCommission.id == commission_id)
        )
        comm = comm_res.scalars().first()
        if not comm or comm.status == "paid":
            return comm

        now = datetime.utcnow()

        # 1. Credit referrer wallet
        ref_wallet_res = await db.execute(
            select(Wallet).filter(
                Wallet.user_id == comm.referrer_id,
                Wallet.currency == comm.currency,
            )
        )
        ref_wallet = ref_wallet_res.scalars().first()
        if not ref_wallet:
            ref_wallet = Wallet(
                user_id=comm.referrer_id,
                currency=comm.currency,
                balance=comm.commission_amount,
                frozen_balance=Decimal("0.0"),
                total_deposited=Decimal("0.0"),
                total_withdrawn=Decimal("0.0"),
            )
            db.add(ref_wallet)
        else:
            ref_wallet.balance += comm.commission_amount
            db.add(ref_wallet)

        # 2. Mark commission paid
        comm.status = "paid"
        comm.paid_at = now
        db.add(comm)

        # 3. Update or create transaction in ledger
        tx_check = await db.execute(
            select(Transaction).filter(
                (Transaction.reference.ilike(f"REF-{comm.id.hex[:10]}%")) |
                (
                    (Transaction.user_id == comm.referrer_id) &
                    (Transaction.type == "referral_bonus") &
                    (Transaction.amount == comm.commission_amount) &
                    (Transaction.status == "pending")
                )
            )
        )
        existing_tx = tx_check.scalars().first()
        if existing_tx:
            existing_tx.status = "completed"
            existing_tx.updated_at = now
            db.add(existing_tx)
        else:
            new_tx = Transaction(
                user_id=comm.referrer_id,
                type="referral_bonus",
                subtype="affiliate_commission",
                amount=comm.commission_amount,
                fee=Decimal("0.0"),
                currency=comm.currency,
                status="completed",
                reference=f"REF-{comm.id.hex[:12].upper()}",
                description=f"Affiliate commission payout ({comm.currency})",
                created_at=now,
            )
            db.add(new_tx)

        # 4. Synchronize referrer's referral_earnings column
        ref_user_res = await db.execute(select(User).filter(User.id == comm.referrer_id))
        referrer = ref_user_res.scalars().first()
        if referrer:
            referrer.referral_earnings = (referrer.referral_earnings or Decimal("0.0")) + comm.commission_amount
            db.add(referrer)

        # 5. Notify referrer
        await notification_service.create_notification(
            db,
            user_id=comm.referrer_id,
            type="referral_commission",
            title="Referral Commission Paid! 💸",
            message=f"You received a referral bonus of {comm.commission_amount} {comm.currency}.",
        )

        return comm

    @staticmethod
    async def reconcile_referrals(db: AsyncSession) -> Dict[str, Any]:
        """Safe administrative audit and reconciliation of referral counts, commissions, and earnings."""
        # 1. Reconcile all user referral counts
        all_referrers_res = await db.execute(
            select(User.referred_by).filter(User.referred_by != None).distinct()
        )
        referrer_ids = [r for r in all_referrers_res.scalars().all() if r]

        reconciled_referrers = 0
        for r_id in referrer_ids:
            count_res = await db.execute(
                select(func.count(User.id)).filter(User.referred_by == r_id)
            )
            count = count_res.scalar() or 0

            # Calculate total paid earnings
            comm_sum_res = await db.execute(
                select(func.sum(ReferralCommission.commission_amount)).filter(
                    ReferralCommission.referrer_id == r_id,
                    ReferralCommission.status == "paid",
                )
            )
            total_earned = comm_sum_res.scalar() or Decimal("0.0")

            u_res = await db.execute(select(User).filter(User.id == r_id))
            referrer = u_res.scalars().first()
            if referrer:
                referrer.referral_count = count
                referrer.referral_earnings = total_earned
                db.add(referrer)
                reconciled_referrers += 1

        # 2. Check for matured investments with pending commissions
        matured_pending_res = await db.execute(
            select(ReferralCommission, Investment)
            .join(Investment, ReferralCommission.investment_id == Investment.id)
            .filter(
                ReferralCommission.status == "pending",
                Investment.status.in_(["completed", "matured"]),
            )
        )
        matured_comms = matured_pending_res.all()
        settled_count = 0
        for comm, inv in matured_comms:
            await ReferralService.settle_referral_commission(db, comm.id)
            settled_count += 1

        await db.commit()

        return {
            "reconciled_referrers": reconciled_referrers,
            "settled_matured_commissions": settled_count,
            "message": f"Successfully reconciled {reconciled_referrers} affiliate accounts and settled {settled_count} matured commissions.",
        }


referral_service = ReferralService()
